// Numbers the pages state, read out of the code that decides them.
//
// "ten sinks", "eleven detection rules", "nineteen sources": each of those is
// a fact about the Go code, and each was a literal in prose that nothing held
// to the code. Adding a sink meant remembering every page that counts them.
//
// So they are derived instead, into src/data/stats.json, and the pages
// interpolate them through <Stat>. `pnpm run stats:check` fails when the file
// disagrees with the code, which is what turns "somebody remembers" into a
// gate.
//
// Every extraction below is anchored on a declaration that exists for its own
// reasons — `sinkFlags.any()`, `derive.Rules`, the usage text, the agent's
// capability map — and each one throws if it cannot find it, rather than
// quietly reporting zero.
//
// Usage: node scripts/gen-stats.mjs           # write src/data/stats.json
//        node scripts/gen-stats.mjs --check   # fail if it is stale
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const SITE = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const REPO = path.dirname(SITE);
const OUT = path.join(SITE, "src/data/stats.json");

const read = (rel) => readFileSync(path.join(REPO, rel), "utf8");

/** The one match of `pattern` in `source`, or a named failure. */
function one(source, pattern, what) {
	const match = pattern.exec(source);
	if (!match) throw new Error(`gen-stats: could not find ${what}`);
	return match[1];
}

// The sinks `forward` can write to: the destinations `sinkFlags.any()` tests,
// which is the same list the "at least one sink" error is about. Sink options
// (--elastic-index, --graphite-prefix) are not destinations and are not in it.
const anyBody = one(
	read("cmd/mikroscope/sinkflags.go"),
	/func \(s \*sinkFlags\) any\(\) bool \{\n\treturn ([\s\S]*?)\n\}/,
	"sinkFlags.any()",
);
const sinks = [...anyBody.matchAll(/s\.(\w+)\s*!=\s*""/g)].map((m) => m[1]);

// The verbs, from the usage text every `mikroscope` with no arguments prints.
const verbBlock = one(
	read("cmd/mikroscope/main.go"),
	/\nverbs\n([\s\S]*?)\n\n/,
	"the verbs block of the usage text",
);
// Two spaces then the verb. `\s{2,}` would have missed `dashboards`, whose
// line runs `dashboards gen | import | check — …` with one space after it;
// continuation lines are indented far deeper and cannot match.
const verbs = [...verbBlock.matchAll(/^ {2}(\w[\w-]*) /gm)].map((m) => m[1]);

// The detection rules, from the list the derive stage publishes so that a sink
// can render a counter per rule before the first event.
// An entry is a string literal or the name of a string constant declared in the
// same file (the informational rules are named once, as constants, so Rules,
// derive.Informational and the code that fires them agree on the spelling);
// a name with no declaration fails the build rather than drop the rule.
const deriveSource = read("internal/derive/derive.go");
const ruleList = one(
	deriveSource,
	/var Rules = \[\]string\{([^}]*)\}/,
	"derive.Rules",
);
const detectionRules = ruleList
	.split(",")
	.map((entry) => entry.trim())
	.filter(Boolean)
	.map((entry) => {
		const literal = /^"([^"]+)"$/.exec(entry);
		if (literal) return literal[1];
		const constant = new RegExp(`^\\s*${entry}\\s*=\\s*"([^"]+)"`, "m").exec(
			deriveSource,
		);
		if (!constant)
			throw new Error(
				`gen-stats: derive.Rules names ${entry}, which is neither a string nor a constant in derive.go`,
			);
		return constant[1];
	});

// The /proc, /sys and /dev sources the agent reports in /capabilities.
const sourceMap = one(
	read("internal/agent/source.go"),
	/Sources: map\[string\]bool\{([\s\S]*?)\n\t\t\},/,
	"the agent's Sources map",
);
const agentSources = [...sourceMap.matchAll(/"([a-z]+)":/g)].map((m) => m[1]);

const stats = {
	// A comment for whoever opens the JSON, since JSON cannot carry one.
	_: "Generated by site/scripts/gen-stats.mjs from the Go source. Do not edit; run `pnpm run stats` in site/.",
	sinks: sinks.length,
	sinkNames: sinks,
	verbs: verbs.length,
	verbNames: verbs,
	detectionRules: detectionRules.length,
	detectionRuleNames: detectionRules,
	agentSources: agentSources.length,
	agentSourceNames: agentSources.sort(),
};

for (const [key, value] of Object.entries(stats)) {
	if (Array.isArray(value) ? value.length === 0 : value === 0) {
		throw new Error(`gen-stats: ${key} came out empty, which cannot be right`);
	}
}

// Two spaces, because that is what prettier writes for JSON here and
// `format:check` is one of the gates: a generated file that prettier would
// reformat turns every run of the linter into a diff.
const rendered = `${JSON.stringify(stats, null, 2)}\n`;
if (process.argv.includes("--check")) {
	const current = readFileSync(OUT, "utf8");
	if (current !== rendered) {
		console.error(
			"[stats] src/data/stats.json is stale against the Go source. Run `pnpm run stats`.",
		);
		process.exit(1);
	}
	console.log(
		`[stats] up to date: ${stats.sinks} sinks, ${stats.verbs} verbs, ${stats.detectionRules} detection rules, ${stats.agentSources} agent sources.`,
	);
} else {
	writeFileSync(OUT, rendered);
	console.log(
		`[stats] wrote src/data/stats.json: ${stats.sinks} sinks, ${stats.verbs} verbs, ${stats.detectionRules} detection rules, ${stats.agentSources} agent sources.`,
	);
}
